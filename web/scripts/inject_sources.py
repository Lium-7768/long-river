def inject(path, dyn):
    s = open(path, encoding='utf-8').read()
    mp = SRC[dyn]
    default = mp['default']

    # 逐条：在 `desc: '...',` 行之后插入 source（仅在 institutions/events/culture 块）
    out = []
    lines = s.split('\n')
    i = 0
    cur_name = None
    in_body = False  # 是否在 institutions/events/culture 块
    while i < len(lines):
        ln = lines[i]
        # 进入/退出内容块
        if re.match(r'\s*(institutions|events|culture)\s*:', ln):
            in_body = True
        elif re.match(r'\s*(territory|completeness|sources)\s*:', ln):
            in_body = False

        m = re.match(r"\s*name:\s*'([^']+)'", ln)
        if m:
            cur_name = m.group(1)

        out.append(ln)

        # 找到该条的 desc 行
        if in_body and re.match(r"\s*desc:\s*'", ln):
            # 若下一条已是 source 则跳过
            nxt = lines[i+1] if i+1 < len(lines) else ''
            if 'source:' not in nxt:
                src = mp.get(cur_name, default)
                indent = re.match(r'(\s*)', ln).group(1)
                out.append(f"{indent}source: '{src}',")
        i += 1

    s2 = '\n'.join(out)

    # 顶部加 sources 数组（在 completeness 前）
    src_list = DY_SOURCES[dyn]
    arr = '  sources: [\n' + ''.join(f"    '{x}',\n" for x in src_list) + '  ],\n'
    s2 = s2.replace('  completeness:', arr + '  completeness:', 1)

    open(path, 'w', encoding='utf-8').write(s2)
    n_src = s2.count('source:')
    print(f"✓ {dyn}: 注入 {n_src} 条 source")


for dyn in ['qin', 'han-w', 'han-e', 'tang', 'ming', 'qing']:
    inject(f'content/profiles/{dyn}.ts', dyn)
