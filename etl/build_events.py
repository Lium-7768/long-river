def main():
    con = sqlite3.connect(DB)
    con.execute("PRAGMA journal_mode=WAL")
    # 扩展 events 表
    cols = [r[1] for r in con.execute("PRAGMA table_info(events)")]
    if 'summary' not in cols:
        con.execute("ALTER TABLE events ADD COLUMN summary TEXT")
    if 'persons' not in cols:
        con.execute("ALTER TABLE events ADD COLUMN persons TEXT")
    # 已有名的集合（避免重复）
    existing = {r[0] for r in con.execute("SELECT name FROM events")}
    maxid = con.execute("SELECT COALESCE(MAX(event_id),0) FROM events").fetchone()[0]
    n = 0
    for dyn, name, fy, ly, summary, persons in EVENTS:
        if name in existing:
            continue
        maxid += 1
        con.execute("INSERT INTO events(event_id,name,fy,ly,dynasty_id,addr,source,summary,persons) "
                    "VALUES (?,?,?,?,?,?,?,?,?)",
                    (maxid, name, fy, ly, dyn, '', '公版史学年表', summary, '、'.join(persons)))
        n += 1
    con.commit()
    print(f"✓ 新增事件 {n}，events 总 {con.execute('SELECT COUNT(*) FROM events').fetchone()[0]}")
    for r in con.execute("SELECT dynasty_id,name,fy,ly FROM events WHERE source='公版史学年表' LIMIT 8"):
        print("  ", r)
    con.close()


if __name__ == "__main__":
    main()
