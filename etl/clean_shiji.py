def is_person(name):
    if not re.fullmatch(r"[\u4e00-\u9fff]{2,4}", name):
        return False
    if name in ("天下", "於是", "是以", "所以", "诸侯", "百姓", "天子", "君子", "小人"):
        return False
    for bs in BAD_START:
        if name.startswith(bs):
            return False
    # 复姓开头 → 允许
    for c in COMPOUND:
        if name.startswith(c) and len(name) >= len(c) + 1:
            return True
    # 单姓 + 名
    if name[0] in SURNAMES:
        # 名不能以虚词结尾
        if name[-1] in "之而不於以者为也与其乃则且夫唯之":
            return False
        return True
    return False


