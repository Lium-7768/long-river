#!/usr/bin/env python3
"""
SQLite → PostgreSQL 数据导入（长河 58 张自有表）。

特点：
- 用 PostgreSQL COPY 协议高速灌入（比逐行 INSERT 快 1-2 个数量级）
- 流式处理，不把整表读进内存（texts 表 4GB+ 单列大字段）
- 自增表用 GENERATED BY DEFAULT AS IDENTITY → 需 COPY 后 setval 重置序列
- 类型归一：SQLite 动态类型 → PG 严格类型（整数列里的脏字符串会被清成 NULL）

用法：
  export PGDATABASE=longriver PGHOST=... PGUSER=... PGPASSWORD=...
  python3 etl/migrate_pg/import_data.py            # 全量
  python3 etl/migrate_pg/import_data.py persons    # 指定表
  python3 etl/migrate_pg/import_data.py --schema   # 只建 schema
"""
import argparse
import io
import os
import re
import sqlite3
import sys
import time

DB = 'file:data/db/lr-song.sqlite3?mode=ro'
BATCH = 50_000

try:
    import psycopg2
except ImportError:
    sys.exit('需要 psycopg2：pip install psycopg2-binary')


def own_tables(con):
    return [
        r[0]
        for r in con.execute(
            "SELECT name FROM sqlite_master WHERE type='table' "
            "AND name NOT LIKE 'cbdb_%' AND name NOT LIKE 'sqlite_%' ORDER BY name"
        )
    ]


def pg_cols(con, t):
    """PG 侧列顺序（与 SQLite 一致，identity 列也 COPY 显式值）"""
    return [c[1] for c in con.execute(f'PRAGMA table_info("{t}")')]


def identity_col(con, t):
    for c in con.execute(f'PRAGMA table_info("{t}")'):
        if c[5] == 1 and c[2].upper() == 'INTEGER':
            sql = con.execute("SELECT sql FROM sqlite_master WHERE name=?", (t,)).fetchone()[0]
            if 'AUTOINCREMENT' in sql.upper():
                return c[1]
    return None


def coerce(val, pgtype):
    """SQLite 动态类型 → PG 严格类型的兜底"""
    if val is None:
        return None
    if pgtype == 'bigint':
        if isinstance(val, bool):
            return int(val)
        if isinstance(val, int):
            return val
        if isinstance(val, float):
            return int(val) if val.is_integer() else None
        if isinstance(val, (bytes, bytearray)):
            val = val.decode('utf-8', 'replace')
        if isinstance(val, str):
            s = val.strip()
            # SQLite 里可能存了 '123' 或脏值
            try:
                return int(s)
            except ValueError:
                try:
                    f = float(s)
                    return int(f) if f.is_integer() else None
                except ValueError:
                    return None
        return None
    if pgtype == 'double precision':
        if isinstance(val, (int, float)):
            return float(val)
        if isinstance(val, str):
            try:
                return float(val.strip())
            except ValueError:
                return None
        return None
    # text
    if isinstance(val, (bytes, bytearray)):
        return val.decode('utf-8', 'replace')
    if isinstance(val, float):
        # 避免 '1.0' 这种意外；整数值转 int 字符串
        return str(int(val)) if val.is_integer() else repr(val)
    return str(val) if not isinstance(val, str) else val


def import_table(pg, scon, t):
    cols = pg_cols(scon, t)
    # PG 侧类型（用 psycopg2 的 description 拿不到，改为从 schema 注释推断不可行；
    # 这里用 SQLite 类型 + UNTYPED 规则，与 convert_schema.py 保持一致）
    from convert_schema import UNTYPED, pg_type
    types = []
    for cid, name, ctype, *_ in scon.execute(f'PRAGMA table_info("{t}")'):
        types.append(pg_type(ctype, t, name))

    collist = ', '.join(f'"{c}"' for c in cols)
    cur = pg.cursor()
    cur.execute(f'TRUNCATE TABLE "{t}" RESTART IDENTITY')

    ident = identity_col(scon, t)
    total = 0
    t0 = time.time()
    buf = io.StringIO()
    n = 0

    def flush():
        nonlocal buf, n, total
        if not n:
            return
        data = buf.getvalue()
        buf = io.StringIO()
        cnt = n
        n = 0
        cur.copy_expert(
            f'COPY "{t}" ({collist}) FROM STDIN WITH (FORMAT csv, NULL \'\\N\')',
            io.StringIO(data),
        )
        total += cnt

    import csv
    writer = csv.writer(buf, quoting=csv.QUOTE_MINIMAL, lineterminator='\n')
    for row in scon.execute(f'SELECT {collist} FROM "{t}"'):
        out = []
        for v, ty in zip(row, types):
            v = coerce(v, ty)
            if v is None:
                out.append('\\N')  # NULL 哨兵（区别于真空字符串）
            elif isinstance(v, int):
                out.append(str(v))
            elif isinstance(v, float):
                out.append(repr(v))
            else:
                out.append(str(v).replace('\x00', ''))
        writer.writerow(out)
        n += 1
        if n >= BATCH:
            flush()
            # writer 仍绑定旧 buffer，需重新指向新 buffer
            writer = csv.writer(buf, quoting=csv.QUOTE_MINIMAL, lineterminator='\n')
    flush()
    pg.commit()

    # 重置 identity 序列
    if ident:
        cur.execute(
            f"SELECT setval(pg_get_serial_sequence('{t}', '{ident}'), "
            f"COALESCE((SELECT MAX(\"{ident}\") FROM \"{t}\"), 0) + 1, false)"
        )
        pg.commit()
    cur.close()
    dt = time.time() - t0
    print(f'  ✓ {t:<28} {total:>9,} 行  {dt:6.1f}s')
    return total


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('tables', nargs='*', help='指定表（默认全部）')
    ap.add_argument('--schema', action='store_true', help='只建 schema，不导数据')
    ap.add_argument('--dsn', default=os.environ.get('DATABASE_URL'), help='PG 连接串')
    a = ap.parse_args()

    if not a.dsn:
        sys.exit('缺少 DSN：设置 DATABASE_URL 或传 --dsn')

    scon = sqlite3.connect(DB, uri=True)
    tables = a.tables or own_tables(scon)

    pg = psycopg2.connect(a.dsn)
    pg.set_session(autocommit=False)

    if a.schema:
        # 建表（交给外部 SQL 更清晰，这里仅提示）
        print('请先执行：python3 etl/migrate_pg/convert_schema.py | psql "$DATABASE_URL"')
        return

    print(f'== 导入 {len(tables)} 张表 → PostgreSQL')
    t0 = time.time()
    grand = 0
    for t in tables:
        grand += import_table(pg, scon, t)
    print(f'== 完成 {grand:,} 行，耗时 {time.time() - t0:.1f}s')
    pg.close()


if __name__ == '__main__':
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    main()
