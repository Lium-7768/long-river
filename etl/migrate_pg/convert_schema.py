#!/usr/bin/env python3
"""
SQLite → PostgreSQL schema 转换（长河 58 张自有表）。

规则（本项目 SQLite schema 极干净：无外键/视图/触发器，仅 INTEGER/TEXT/REAL）：

| SQLite | PostgreSQL |
|---|---|
| INTEGER PRIMARY KEY AUTOINCREMENT | bigint GENERATED BY DEFAULT AS IDENTITY |
| INTEGER PK / TEXT PK | 保留类型，加 PRIMARY KEY |
| INTEGER | bigint（容纳有符号生卒年，负数=公元前） |
| REAL | double precision |
| TEXT | text |
| INT | bigint |
| 无类型声明 | 按实际数据推断（aliases.source→text, record_count/cbdb_count→bigint） |

不迁移：
  - `cbdb_*` 78 张原料表（前端不直连，仅作 ETL 输入）
  - `sqlite_*` SQLite 内部表

用法：
  python3 etl/migrate_pg/convert_schema.py > /tmp/pg_schema.sql
  psql "$DSN" -f /tmp/pg_schema.sql
"""
import re
import sqlite3
import sys

DB = 'file:data/db/lr-song.sqlite3?mode=ro'

# 无类型列的推断（SQLite 允许省略类型）
UNTYPED = {
    ('aliases', 'source'): 'text',
    ('person_canonical', 'record_count'): 'bigint',
    ('person_canonical', 'cbdb_count'): 'bigint',
}

SKIP = {'sqlite_sequence', 'sqlite_stat1', 'sqlite_stat4'}


def own_tables(con):
    return [
        r[0]
        for r in con.execute(
            "SELECT name FROM sqlite_master WHERE type='table' "
            "AND name NOT LIKE 'cbdb_%' AND name NOT LIKE 'sqlite_%' ORDER BY name"
        )
    ]


def col_info(con, t):
    """[(cid,name,type,notnull,dflt,pk)]"""
    return list(con.execute(f'PRAGMA table_info("{t}")'))


def pg_type(sqlite_type: str, table: str, col: str) -> str:
    key = (table, col)
    if not sqlite_type:
        return UNTYPED.get(key, 'text')
    up = sqlite_type.upper()
    if up in ('INT', 'INTEGER', 'BIGINT'):
        return 'bigint'
    if up in ('REAL', 'FLOAT', 'DOUBLE'):
        return 'double precision'
    if up in ('BLOB',):
        return 'bytea'
    return 'text'


def convert() -> str:
    con = sqlite3.connect(DB, uri=True)
    out = ['-- 长河 · PostgreSQL schema（由 convert_schema.py 自动生成）',
           '-- 来源：data/db/lr-song.sqlite3 自有 58 表；不含 cbdb_* 原料表', '']

    for t in own_tables(con):
        cols = col_info(con, t)
        sql = con.execute("SELECT sql FROM sqlite_master WHERE name=?", (t,)).fetchone()[0]
        is_auto = 'AUTOINCREMENT' in sql.upper()

        lines = []
        # 先判断是否复合主键：若是，单列一律不加 PRIMARY KEY，统一在末尾声明
        n_pk = sum(1 for c in cols if c[5])
        composite = n_pk > 1
        for c in cols:
            cid, name, ctype, notnull, dflt, pk = c
            pg = pg_type(ctype, t, name)
            is_identity = is_auto and pk == 1
            if is_identity:
                # PG identity 自带唯一/非空
                lines.append(f'  "{name}" bigint GENERATED BY DEFAULT AS IDENTITY')
                continue
            frag = f'  "{name}" {pg}'
            if pk == 1 and not composite:
                frag += ' PRIMARY KEY'
            elif notnull:
                frag += ' NOT NULL'
            if dflt is not None:
                frag += f' DEFAULT {dflt}'
            lines.append(frag)

        # 复合主键
        if composite:
            multi = [c[1] for c in sorted(cols, key=lambda x: x[5]) if c[5] > 0]
            lines.append('  PRIMARY KEY (' + ', '.join(f'"{m}"' for m in multi) + ')')

        out.append(f'CREATE TABLE IF NOT EXISTS "{t}" (')
        out.append(',\n'.join(lines))
        out.append(');')
        out.append('')

    # 索引
    idx = con.execute(
        "SELECT name, tbl_name, sql FROM sqlite_master WHERE type='index' "
        "AND sql IS NOT NULL AND tbl_name NOT LIKE 'cbdb_%' AND tbl_name NOT LIKE 'sqlite_%' "
        "ORDER BY tbl_name, name"
    ).fetchall()
    if idx:
        out.append('-- 索引')
        out.append('')
    for name, tbl, sql in idx:
        s = sql.strip()
        # CREATE [UNIQUE] INDEX name ON tbl (...) —— PG 兼容，仅需 IF NOT EXISTS
        s = re.sub(r'^CREATE\s+(UNIQUE\s+)?INDEX\s+',
                   lambda m: f'CREATE {m.group(1) or ""}INDEX IF NOT EXISTS ', s, flags=re.I)
        out.append(s + ';')

    con.close()
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    sys.stdout.write(convert())
